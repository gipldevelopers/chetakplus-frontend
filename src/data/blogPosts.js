export const getBlogPostBySlug = (slug) =>
  blogPosts.find((post) => post.slug === slug);

export const getRelatedBlogPosts = (slug, category) =>
  blogPosts
    .filter((post) => post.slug !== slug)
    .sort((firstPost, secondPost) => {
      if (firstPost.category === category && secondPost.category !== category) {
        return -1;
      }

      if (firstPost.category !== category && secondPost.category === category) {
        return 1;
      }

      return 0;
    })
    .slice(0, 3);
